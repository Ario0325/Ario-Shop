"""One-off: extract the molla icon font layer out of legacy style.css.

Writes static/assets/css/ario-icons.css so the 500KB Porto stylesheet can be
dropped from the page without losing every <i class="icon-*"> glyph.
"""
from pathlib import Path

root = Path(__file__).resolve().parents[1]
src = root / "static" / "assets" / "css" / "style.css"
out = root / "static" / "assets" / "css" / "ario-icons.css"

css = src.read_text(encoding="utf-8", errors="replace")
molla = css.index("molla0ab2")
start = css.rindex("@font-face", 0, molla)
last_icon = css.index(".icon-yarn:before")
end = css.index("}", last_icon) + 1
block = css[start:end]

header = (
    '@charset "UTF-8";\n'
    "/* ==========================================================================\n"
    "   Ario Shop - Icon layer (extracted from legacy Porto style.css)\n"
    '   Self-hosted "molla" icon font faces + .icon-* glyph map only.\n'
    "   Generated by tools/extract_icons.py - do not edit by hand.\n"
    "   ========================================================================== */\n\n"
)
out.write_text(header + block + "\n", encoding="utf-8")

checks = [".icon-search:before", ".icon-star:before", ".icon-user:before",
          ".icon-shopping-cart:before", ".icon-heart-o:before", ".icon-long-arrow-left:before"]
print(f"wrote {out} ({out.stat().st_size} bytes)")
print(f"range {start}-{end}")
for c in checks:
    print(f"  {c:34s} {c in block}")
print("  @font-face count:", block.count("@font-face"))
